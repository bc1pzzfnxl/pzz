#!/usr/bin/env node
// Generates worker/llms.txt and skills/frontend-toolbox/SKILL.md from tools.json.
//
// tools.json is the only hand-maintained input (name, url, use). Everything else
// is extracted from each site: an `llms.txt` when it exists, otherwise the page's
// <title> / <meta name="description"> / og:description.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const { homepage, tools } = JSON.parse(readFileSync(join(root, "tools.json"), "utf8"));

const UA = { "user-agent": "Mozilla/5.0 (compatible; frontend-toolbox-builder/1.0)" };

// Prefer an explicit token (CI). Locally, fall back to the already-authenticated
// GitHub CLI so no secret has to be stored or pasted anywhere.
function resolveGithubToken() {
  const fromEnv = process.env.GITHUB_TOKEN || process.env.GH_TOKEN;
  if (fromEnv) return fromEnv.trim();
  try {
    return execFileSync("gh", ["auth", "token"], { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).trim() || null;
  } catch {
    return null;
  }
}

const GITHUB_TOKEN = resolveGithubToken();

function firstMatch(html, patterns) {
  for (const re of patterns) {
    const m = html.match(re);
    if (m?.[1]) return m[1].replace(/<[^>]*>/g, "").replace(/\s+/g, " ").trim();
  }
  return null;
}

async function githubDesc(repo) {
  if (!repo) return null;
  try {
    const headers = { ...UA, accept: "application/vnd.github+json" };
    if (GITHUB_TOKEN) headers.authorization = `Bearer ${GITHUB_TOKEN}`;
    const res = await fetch(`https://api.github.com/repos/${repo}`, { headers });
    if (!res.ok) return null;
    const data = await res.json();
    return typeof data.description === "string" && data.description ? data.description : null;
  } catch {
    return null;
  }
}

async function extract(tool) {
  const origin = new URL(tool.url).origin;
  let desc = null;
  let llmsUrl = null;

  try {
    const res = await fetch(tool.url, { redirect: "follow", headers: UA });
    const html = await res.text();
    desc = firstMatch(html, [
      /<meta[^>]+name=["']description["'][^>]+content=["']([^"']*)/i,
      /<meta[^>]+content=["']([^"']*)["'][^>]+name=["']description["']/i,
      /<meta[^>]+property=["']og:description["'][^>]+content=["']([^"']*)/i,
    ]);
  } catch {
    console.warn(`! could not fetch ${tool.url}`);
  }

  if (!desc) desc = await githubDesc(tool.repo);

  try {
    const res = await fetch(`${origin}/llms.txt`, { redirect: "follow", headers: UA });
    if (res.ok) llmsUrl = `${origin}/llms.txt`;
  } catch {}

  return { ...tool, desc, llmsUrl, bestUrl: llmsUrl ?? tool.url };
}

const enriched = [];
for (const tool of tools) enriched.push(await extract(tool));

// worker/llms.txt
const llms = [
  "# OpenCode Frontend Toolbox",
  "",
  "> Preferred tools for UI/frontend work. Pick the row matching the task, then open its canonical page.",
  "",
  "## Tools",
  "",
];
for (const t of enriched) {
  let line = `- [${t.name}](${t.bestUrl}): ${t.use}`;
  if (t.desc) line += ` — ${t.desc}`;
  llms.push(line);
}
llms.push("");
writeFileSync(join(root, "worker/llms.txt"), llms.join("\n"));

// skills/frontend-toolbox/SKILL.md
const uses = enriched.map((t) => t.use).join(", ");
const rows = enriched.map((t) => `| ${t.use} | ${t.name} | ${t.bestUrl} |`).join("\n");
const skill = `---
name: frontend-toolbox
description: Preferred tools for UI/frontend work. Use whenever a task involves ${uses}.
---

# Frontend toolbox

Default tools for UI work. Pick the row that matches the task, then open its
canonical page before using the tool.

| Task | Tool | Canonical page |
| --- | --- | --- |
${rows}

The canonical, always-current mapping is served at
\`${homepage}\`.
Treat it as the live source of truth and refresh this table from it when it changes.

<!-- Generated by scripts/generate.mjs from tools.json — do not edit by hand. -->
`;
writeFileSync(join(root, "skills/frontend-toolbox/SKILL.md"), skill);

console.log(`generated ${enriched.length} tools:`);
for (const t of enriched) {
  console.log(`  ${t.name.padEnd(18)} ${t.llmsUrl ? "llms.txt" : "meta    "}${t.desc ? "" : "  (no description)"}`);
}
