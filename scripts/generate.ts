#!/usr/bin/env bun
// Renders toolbox.md and one skill per tool from pzz.json. No network: the
// source and description of each tool are verified when the tool is added.
import {
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { join } from "node:path";
import { loadConfig, repoRoot } from "./lib/config.ts";
import { renderSkill, renderToolbox, skillName } from "./lib/render.ts";

const config = loadConfig();
const skillsDir = join(repoRoot, "skills");
const generated = new Set(config.tools.map(skillName));

writeFileSync(join(repoRoot, "toolbox.md"), renderToolbox(config));

mkdirSync(skillsDir, { recursive: true });
for (const tool of config.tools) {
  const dir = join(skillsDir, skillName(tool));
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, "SKILL.md"), renderSkill(tool, config.docUrl));
}

// Remove skills this generator produced earlier for tools that no longer exist.
for (const entry of readdirSync(skillsDir, { withFileTypes: true })) {
  if (!entry.isDirectory() || generated.has(entry.name)) continue;
  const file = join(skillsDir, entry.name, "SKILL.md");
  if (
    existsSync(file) &&
    readFileSync(file, "utf8").includes("Generated by scripts/generate")
  ) {
    rmSync(join(skillsDir, entry.name), { recursive: true });
    console.log(`removed stale skill ${entry.name}`);
  }
}

console.log(`generated toolbox.md and ${config.tools.length} skills:`);
for (const tool of config.tools) {
  console.log(`  ${skillName(tool).padEnd(18)} ${tool.source}`);
}
